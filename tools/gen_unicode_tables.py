"""Generate compact Unicode category range tables for the qwen2 pre-tokenizer.

We need exactly two predicates, because Qwen2's pre-tokenization regex uses
\\p{L} (letters) and \\p{N} (numbers):

    (?i:'s|'t|'re|'ve|'m|'ll|'d)|[^\\r\\n\\p{L}\\p{N}]?\\p{L}+|\\p{N}| ?[^\\s\\p{L}\\p{N}]+[\\r\\n]*|\\s*[\\r\\n]+|\\s+(?!\\S)|\\s+

The tables are generated rather than hand-written so they can be regenerated for
a newer Unicode version:

    python tools/gen_unicode_tables.py > src/unicode_tables.h
"""
import sys
import unicodedata

MAX_CP = 0x110000


def ranges_for(predicate):
    out = []
    start = None
    for cp in range(MAX_CP):
        # surrogates are not valid scalar values
        ok = not (0xD800 <= cp <= 0xDFFF) and predicate(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX_CP - 1))
    return out


def cat_is(*prefixes):
    def pred(ch):
        try:
            return unicodedata.category(ch)[0] in prefixes or unicodedata.category(ch) in prefixes
        except Exception:
            return False
    return pred


def emit(name, rs):
    print(f"static const CodeRange {name}[] = {{")
    for i in range(0, len(rs), 4):
        chunk = rs[i:i + 4]
        line = "    " + " ".join(f"{{0x{a:05X}, 0x{b:05X}}}," for a, b in chunk)
        print(line)
    print("};")
    print(f"static const size_t {name}_len = sizeof({name}) / sizeof({name}[0]);")
    print()


def main():
    letters = ranges_for(lambda ch: unicodedata.category(ch).startswith("L"))
    numbers = ranges_for(lambda ch: unicodedata.category(ch).startswith("N"))
    # \s in ECMAScript -- an explicit set, not a Unicode property
    ws = [(0x09, 0x0D), (0x20, 0x20), (0xA0, 0xA0), (0x1680, 0x1680),
          (0x2000, 0x200A), (0x2028, 0x2029), (0x202F, 0x202F),
          (0x205F, 0x205F), (0x3000, 0x3000), (0xFEFF, 0xFEFF)]

    print("// GENERATED by tools/gen_unicode_tables.py -- do not edit by hand.")
    print(f"// Unicode {unicodedata.unidata_version}; \\p{{L}} = {len(letters)} ranges,"
          f" \\p{{N}} = {len(numbers)} ranges")
    print("#pragma once")
    print("#include <cstddef>")
    print("#include <cstdint>")
    print()
    print("namespace zen {")
    print("struct CodeRange { uint32_t lo, hi; };")
    print()
    emit("kLetterRanges", letters)
    emit("kNumberRanges", numbers)
    emit("kWhitespaceRanges", ws)
    print("}  // namespace zen")
    return 0


if __name__ == "__main__":
    sys.exit(main())
